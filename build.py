def popular_brands(cat: dict, gender: str, n: int = 8) -> list:
    """Brands that have items of that gender in the sale listing (BS.collections.plp), because every listing link
    lands on the sale page. Ranked by that count, then by the store 'top' flag and the real store count."""
    plp = set(cat.get("collections", {}).get("plp") or [])
    counts = {}
    for p in cat["products"]:
        if p["gender"] == gender and p["id"] in plp:
            counts[p["brandSlug"]] = counts.get(p["brandSlug"], 0) + 1
    ranked = sorted(
        (b for b in cat["brands"] if counts.get(b["slug"])),
        key=lambda b: (-counts[b["slug"]], not b.get("top"), -(b.get("count") or 0)),
    )
    return ranked[:n]


def demo_brand_slugs(cat: dict) -> set:
    """Brand slugs that have at least one product in the demo data (BS.products)."""
    return {p["brandSlug"] for p in cat["products"]}


