def _get(url: str) -> str:
    """Download text. Falls back to the system curl when Python has no CA bundle (python.org builds on macOS)."""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "brandstore-build/1.0"})
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.read().decode("utf-8")
    except Exception:  # noqa: BLE001
        res = subprocess.run(["curl", "-sfL", "--max-time", "30", url], capture_output=True)
        if res.returncode != 0:
            raise RuntimeError(f"download failed: {url}")
        return res.stdout.decode("utf-8")


def fetch_icons() -> None:
    symbols, missing = [], []
    jobs = [(n, "light", "-light", f"i-{n}") for n in ICONS_LIGHT] + [(n, "fill", "-fill", f"i-{n}-fill") for n in ICONS_FILL]
    for name, weight, suffix, sid in jobs:
        try:
            svg = _get(PHOSPHOR.format(weight=weight, name=name, suffix=suffix))
        except Exception as exc:  # noqa: BLE001
            missing.append(f"{weight}/{name} ({exc})")
            continue
        vb = re.search(r'viewBox="([^"]+)"', svg)
        inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg.strip(), flags=re.S)
        symbols.append(f'<symbol id="{sid}" viewBox="{vb.group(1) if vb else "0 0 256 256"}">{inner}</symbol>')
    if not symbols:
        raise SystemExit("icons: nothing downloaded, keeping the existing sprite")
    sprite = (
        "<!-- Phosphor Icons (light + fill), MIT, https://phosphoricons.com. Generated by build.py --fetch-icons -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" class="icon-sprite" aria-hidden="true" focusable="false" '
        'style="position:absolute;width:0;height:0;overflow:hidden">\n' + "\n".join(symbols) + "\n</svg>\n"
    )
    (PARTIALS / "icons.svg").write_text(sprite, encoding="utf-8")
    print(f"icons: {len(symbols)} symbols -> src/partials/icons.svg")
    if missing:
        print("icons: MISSING " + ", ".join(missing))

    marks = []
    for slug, label in PAYMENT_MARKS:
        svg = _get(f"https://cdn.simpleicons.org/{slug}")
        inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg.strip(), flags=re.S)
        inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)
        marks.append(
            f'<li class="pay-mark" title="{label}"><svg class="pay-mark__svg" viewBox="0 0 24 24" role="img" '
            f'aria-label="{label}" fill="currentColor">{inner}</svg></li>'
        )
    marks.append('<li class="pay-mark pay-mark--text">El. bankininkystė</li>')
    (PARTIALS / "payment-marks.html").write_text(
        "<!-- Simple Icons (CC0), https://simpleicons.org. Generated by build.py --fetch-icons -->\n"
        + "\n".join(marks) + "\n", encoding="utf-8")
    print("payments: src/partials/payment-marks.html")


# --------------------------------------------------------------- helpers ----
def esc(s) -> str:
    return html.escape(str(s), quote=True)


def fmt_num(n) -> str:
    s = f"{int(round(n)):,}".replace(",", NBSP)
    return s


def plural(n: int, forms) -> str:
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return forms[0]
    if 2 <= n % 10 <= 9 and not 11 <= n % 100 <= 19:
        return forms[1]
    return forms[2]


def norm(s: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFD", s) if unicodedata.category(c) != "Mn").lower()


def url(params: dict) -> str:
    from urllib.parse import urlencode
    return "parduotuve.html?" + esc(urlencode(params))


def icon(name: str, cls: str = "") -> str:
    c = f"i {cls}".strip()
    return f'<svg class="{c}" aria-hidden="true" focusable="false"><use href="#i-{name}"></use></svg>'


