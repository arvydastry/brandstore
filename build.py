def brand_letter(name: str) -> str:
    ch = norm(name)[:1].upper()
    return ch if ch.isalpha() else "#"


def render_brand_list(brands: list, id_prefix: str, demo: set | None = None) -> str:
    """A-Z brand list. Letters are plain text in a labelled group (not headings), so the header does not put
    19 hidden h3s in front of the page h1. Brands without any demo product keep their real listing link
    (works without JS) but get data-demo-brand: core shows a toast instead of an empty listing."""
    groups: dict[str, list] = {}
    for b in sorted(brands, key=lambda b: norm(b["name"])):
        groups.setdefault(brand_letter(b["name"]), []).append(b)
    out = []
    for letter, items in groups.items():
        lis = "".join(
            f'<li data-brand="{esc(norm(b["name"]))}"><a class="brand-list__link'
            + (f'" href="{url({"zenklas": b["slug"]})}">' if demo is None or b["slug"] in demo
               else f' is-demo-empty" href="{url({"zenklas": b["slug"]})}" data-demo-brand="{esc(b["name"])}">')
            + f'<span>{esc(b["name"])}</span>'
            + (f'<span class="mega__count">{fmt_num(b["count"])}</span>' if b.get("count") else "")
            + "</a></li>"
            for b in items
        )
        out.append(
            f'<div class="brand-group" role="group" data-letter="{letter}" id="{id_prefix}-{letter}" aria-label="{letter}">'
            f'<p class="brand-group__letter" aria-hidden="true">{letter}</p><ul class="brand-group__list" role="list">{lis}</ul></div>'
        )
    return "".join(out), set(groups)


