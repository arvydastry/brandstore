# ------------------------------------------------------------ templating ----
META_RE = re.compile(r"^\s*<!--\s*@page\b(.*?)-->\s*", re.S)
ATTR_RE = re.compile(r'([\w-]+)\s*=\s*"([^"]*)"')
INCLUDE_RE = re.compile(r"<!--\s*@include\s+([\w./-]+)\s*-->")
VAR_RE = re.compile(r"\{\{\s*([\w.-]+)\s*\}\}")


def parse_meta(text: str):
    m = META_RE.match(text)
    if not m:
        return {}, text
    return dict(ATTR_RE.findall(m.group(1))), text[m.end():]


def resolve_includes(text: str, depth: int = 0) -> str:
    if depth > 8:
        raise RuntimeError("include depth exceeded (cycle?)")

    def sub(m):
        name = m.group(1)
        for cand in (PARTIALS / name, PARTIALS / f"{name}.html", PARTIALS / f"{name}.svg"):
            if cand.is_file():
                return resolve_includes(cand.read_text(encoding="utf-8"), depth + 1)
        raise FileNotFoundError(f"@include {name}: no such partial in src/partials/")

    return INCLUDE_RE.sub(sub, text)


def render_vars(text: str, ctx: dict) -> str:
    def sub(m):
        key = m.group(1)
        if key not in ctx:
            raise KeyError(f"template variable {{{{ {key} }}}} is not defined")
        return str(ctx[key])

    return VAR_RE.sub(sub, text)


