def price_html(p: dict, size: str = "", badge: bool = False, cls: str = "") -> str:
    """Mirror of BS.ui.priceHTML (core.js) so static and rendered prices are identical."""
    sz = f" price--{size}" if size else ""
    extra = f" {cls}" if cls else ""
    regular = p.get("regular") or p["price"]
    if regular > p["price"]:
        b = (f' <span class="badge badge--sale{" badge--lg" if size else ""}">{discount_label(p["discount"])}</span>' if badge else "")
        return (
            f'<p class="price price--sale{sz}{extra}"><span class="sr-only">Kaina su nuolaida: </span>'
            f'<span class="price__now">{fmt_price(p["price"])}</span><span class="sr-only">, ankstesnė kaina: </span>'
            f'<s class="price__old">{fmt_price(regular)}</s>{b}</p>'
        )
    return f'<p class="price{sz}{extra}"><span class="price__now">{fmt_price(p["price"])}</span></p>'


