def bar_html(p: dict) -> str:
    sizes = p["sizes"]
    sel = ""
    if len(sizes) > 1:
        opts = ['<option value="" disabled selected>Pasirinkite dydį</option>']
        for s in sizes:
            lab = esc(size_label(s["label"]))
            opts.append(f'<option value="{esc(s["value"])}">{lab}</option>' if s["available"]
                        else f'<option value="{esc(s["value"])}" disabled>{lab}, nėra</option>')
        sel = (
            '<div class="select pdp-bar__select" data-pdp-bar-select>'
            f'<select aria-label="Dydis" data-pdp-bar-size>{"".join(opts)}</select>{icon("caret-down")}'
            '<p class="field__error pdp-bar__error" id="pdp-bar-err" data-pdp-bar-err hidden>Pasirinkite dydį</p></div>'
        )
    else:
        sel = '<p class="pdp-bar__one">Vienas dydis</p>'
    img = p["images"][0]
    cls = "pdp-img " + ("is-packshot" if is_packshot(p, 0) else "is-photo")
    return (
        '<div class="pdp-bar" data-pdp-bar role="region" aria-label="Greitas pirkimas" inert>'
        '<div class="pdp-bar__inner container">'
        f'<div class="pdp-bar__product"><span class="pdp-bar__thumb"><img class="{cls}" src="{esc(img)}" alt="" width="800" height="1200" loading="lazy" decoding="async"></span>'
        f'<span class="pdp-bar__text"><span class="pdp-bar__brand">{esc(p["brand"])}</span><span class="pdp-bar__title">{esc(p["title"])}</span></span></div>'
        f'<div class="pdp-bar__price">{price_html(p, "lg")}</div>'
        f"{sel}"
        '<button class="btn pdp-bar__add" type="button" data-pdp-bar-add>Į krepšelį</button>'
        "</div></div>"
    )


def json_ld(p: dict, cat_url: str, gender_url: str) -> str:
    color = (p.get("colors") or [{}])[0]
    paras = [x.strip() for x in dash_free(p.get("desc") or "").split("\n\n") if x.strip()]
    available = any(s["available"] for s in p["sizes"])
    name = image_alt(p)
    data = {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "Product",
                "name": name,
                "image": p["images"],
                "description": " ".join(paras),
                "sku": p.get("sku"),
                "brand": {"@type": "Brand", "name": p["brand"]},
                "color": color.get("name"),
                "category": f"{GENDER_LABEL.get(p['gender'], '')} > {GROUP_LABEL.get(p['group'], '')} > {p['category']}",
                "offers": {
                    "@type": "Offer",
                    "url": p.get("permalink"),
                    "priceCurrency": "EUR",
                    "price": f"{p['price']:.2f}",
                    "availability": "https://schema.org/InStock" if available else "https://schema.org/OutOfStock",
                    "itemCondition": "https://schema.org/NewCondition",
                    "seller": {"@type": "Organization", "name": "Brandstore.lt"},
                },
            },
            {
                "@type": "BreadcrumbList",
                "itemListElement": [
                    {"@type": "ListItem", "position": 1, "name": "Pradžia", "item": "index.html"},
                    {"@type": "ListItem", "position": 2, "name": GENDER_LABEL.get(p["gender"], ""), "item": gender_url},
                    {"@type": "ListItem", "position": 3, "name": p["category"], "item": cat_url},
                    {"@type": "ListItem", "position": 4, "name": p["title"]},
                ],
            },
        ],
    }
    body = json.dumps(data, ensure_ascii=False, indent=1).replace("</", "<\\/")
    return (
        "<!-- Demo: schema.org Product + BreadcrumbList from catalog.json (WooCommerce/Yoast output this on the live site) -->\n"
        f'<script type="application/ld+json">\n{body}\n</script>'
    )


def render_page(p: dict, cat: dict) -> str:
    meta = cat["meta"]
    gender = p["gender"]
    glabel = GENDER_LABEL.get(gender, "")
    on_sale = (p.get("regular") or p["price"]) > p["price"]
    gender_url = listing_url({"lytis": gender})
    cat_url = listing_url({"lytis": gender, "kategorija": p["wooCategorySlug"]})
    name = image_alt(p)
    title = f"{name} | Brandstore.lt"
    desc = f"{name} už {fmt_price(p['price'])}"
    if on_sale:
        desc += f" vietoj {fmt_price(p['regular'])} ({discount_label(p['discount'])})"
    desc += f". Originali prekė, išsiunčiame per {meta.get('shippingFacts', {}).get('dispatch', '1-2 darbo dienas')}, 14 dienų grąžinimas."
    img0 = p["images"][0]
    guide = size_guide_html(p, meta)

    head = (
        f'<!-- @page title="{meta_attr(title)}" description="{meta_attr(desc)}" body="page-pdp" header="solid" '
        f'css="pdp" js="pdp" nav="{gender}" mobilebar="off" preload="{img0}" og_image="{img0}" -->'
    )
    crumbs = (
        '<nav class="breadcrumbs pdp-crumbs" aria-label="Naršymo kelias"><ol>'
        '<li><a href="index.html">Pradžia</a></li>'
        f'<li><a href="{esc(gender_url)}">{esc(glabel)}</a></li>'
        f'<li><a href="{esc(cat_url)}">{esc(p["category"])}</a></li>'
        f'<li><span aria-current="page">{esc(p["title"])}</span></li>'
        "</ol></nav>"
    )
    back = (
        f'<a class="btn btn--link btn--sm pdp-back" href="{esc(cat_url)}" data-pdp-back hidden>'
        f'{icon("arrow-left", "i--sm")}<span>Atgal į rezultatus</span></a>'
    )
    template = f'<template id="pdp-size-guide">{guide}</template>' if guide else ""
    return "\n".join([
        head,
        MARKER,
        json_ld(p, cat_url, gender_url),
        f'<div class="pdp" data-pdp="{p["id"]}" data-pdp-group="{esc(p["group"])}">',
        '<section class="pdp-main" aria-label="Prekė">',
        '<div class="container">',
        f'<div class="pdp-topline">{crumbs}{back}</div>',
        f'<div class="pdp-grid">{gallery_html(p)}{info_html(p, cat, bool(guide))}</div>',
        "</div>",
        "</section>",
        sections_html(p, cat),
        "</div>",
        lightbox_html(p),
        bar_html(p),
        template,
        "",
    ])


def main() -> None:
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    by_id = {p["id"]: p for p in cat["products"]}
    wanted = set()
    for pid in cat["collections"].get("pdp", []):
        p = by_id.get(int(pid))
        if not p:
            print(f"  pdp: product {pid} not found in catalog.json, skipped")
            continue
        out = PAGES / f"preke-{p['slug']}.html"
        wanted.add(out.name)
        text = render_page(p, cat)
        if "—" in text:
            raise SystemExit(f"pdp: em dash in generated {out.name}")
        old = out.read_text(encoding="utf-8") if out.exists() else None
        if old != text:
            out.write_text(text, encoding="utf-8")
            print(f"  pdp: wrote src/pages/{out.name}")
        else:
            print(f"  pdp: unchanged src/pages/{out.name}")
    # remove pages this generator made for products that are no longer in BS.collections.pdp
    for f in PAGES.glob("preke-*.html"):
        if f.name not in wanted and MARKER in f.read_text(encoding="utf-8"):
            f.unlink()
            print(f"  pdp: removed stale src/pages/{f.name}")


if __name__ == "__main__":
    main()
