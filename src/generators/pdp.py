def esc(s) -> str:
    return html.escape(str(s), quote=True)


def fmt_num(n) -> str:
    return f"{int(round(n)):,}".replace(",", NBSP)


def fmt_price(n) -> str:
    n = float(n)
    if n == int(n):
        return f"{fmt_num(n)}{NBSP}€"
    whole, dec = f"{n:.2f}".split(".")
    return f"{fmt_num(int(whole))},{dec}{NBSP}€"


def discount_label(d) -> str:
    return f"{MINUS}{int(round(abs(d)))}{NBSP}%"


def plural(n: int, forms) -> str:
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return forms[0]
    if 2 <= n % 10 <= 9 and not 11 <= n % 100 <= 19:
        return forms[1]
    return forms[2]


def lc_first(s: str) -> str:
    return s[:1].lower() + s[1:]


def dash_free(s: str) -> str:
    """Same rule as BS.util.dashFree: ' – ' becomes ', ', other dashes become '-'."""
    s = re.sub(r"\s+[–—]\s+", ", ", str(s or ""))
    return re.sub(r"[–—]", "-", s)


def size_label(s: str) -> str:
    return re.sub(r"[–—]", "-", str(s or ""))


def icon(name: str, cls: str = "") -> str:
    c = f"i {cls}".strip()
    return f'<svg class="{c}" aria-hidden="true" focusable="false"><use href="#i-{name}"></use></svg>'


ACC_ICON = '<span class="acc__icon" aria-hidden="true">' + icon("plus", "acc__plus") + icon("minus", "acc__minus") + "</span>"


def listing_url(params: dict) -> str:
    q = {k: v for k, v in params.items() if v not in (None, "", [])}
    return "parduotuve.html" + ("?" + urlencode(q) if q else "")


def image_alt(p: dict) -> str:
    return f"{p['brand']} {lc_first(p['title'])}"


def is_packshot(p: dict, i: int) -> bool:
    if i == 0:
        return p.get("imageBg") == "white"
    return i not in (p.get("modelImages") or [])


def meta_attr(s: str) -> str:
    """Values of the @page comment cannot contain a double quote."""
    return str(s).replace('"', "'").replace("-->", "")


def join_lt(items: list) -> str:
    items = [str(x) for x in items]
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " ir " + items[-1]


