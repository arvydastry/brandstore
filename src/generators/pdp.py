def stock_html(p: dict) -> str:
    st = p.get("stock")
    if st is None or st > 3 or st < 1:
        return ""
    return f'<p class="stock-line">{"Liko paskutinis vienetas" if st == 1 else f"Liko tik {st}"}</p>'


