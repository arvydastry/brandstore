def size_guide_html(p: dict, meta: dict) -> str | None:
    group, gender = p["group"], p["gender"]
    if group == "avalyne":
        chart, kind = SHOES, "Avalynė"
    elif group == "drabuziai" and gender in CLOTHING:
        chart, kind = CLOTHING[gender], "Drabužiai"
    else:
        return None
    rows = []
    for s in p["sizes"]:
        key = s["value"] if s["value"] in chart["rows"] else size_label(s["label"])
        cells = chart["rows"].get(key)
        if not cells:
            continue
        na = "" if s["available"] else ' <span class="pdp-guide__na">nėra</span>'
        tds = "".join(f"<td>{esc(c)}</td>" for c in cells)
        rows.append(
            f'<tr data-size-row="{esc(s["value"])}"><th scope="row">{esc(size_label(s["label"]))}{na}'
            f'<span class="sr-only" data-size-row-sr></span></th>{tds}</tr>'
        )
    if not rows:
        return None
    head = "".join(f'<th scope="col">{esc(h)}</th>' for h in chart["head"])
    how = "".join(f"<li>{esc(h)}</li>" for h in chart["how"])
    who = f"{GENDER_LABEL.get(gender, '')}, {kind.lower()}" if gender in GENDER_LABEL else kind
    return (
        '<div class="pdp-guide">'
        f'<p class="pdp-guide__meta">{esc(p["brand"])} · {esc(who)}</p>'
        '<div class="pdp-guide__scroll" tabindex="0" role="region" aria-label="Dydžių lentelė, slinkite horizontaliai">'
        f'<table class="table pdp-guide__table"><caption class="sr-only">Dydžių atitikmenys: {esc(image_alt(p))}</caption>'
        f"<thead><tr>{head}</tr></thead><tbody>{''.join(rows)}</tbody></table></div>"
        '<p class="pdp-guide__note">Orientaciniai matmenys. Skirtingų prekės ženklų kirpimas gali šiek tiek skirtis.</p>'
        f'<div class="pdp-guide__how"><h3 class="pdp-guide__title">Kaip pasimatuoti</h3><ul>{how}</ul></div>'
        f'<p class="pdp-guide__help">{esc(chart["help"])} '
        f'Reikia patarimo? Skambinkite <a href="tel:{esc(meta["phone"])}">{esc(meta["phoneDisplay"]).replace(" ", NBSP)}</a>.</p>'
        "</div>"
    )


